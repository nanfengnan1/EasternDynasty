import assert from 'node:assert/strict';
import {due,nextAction,validConfig} from '../Automation/policy.mjs';
const now=Date.parse('2026-10-25T12:00:00Z'),past='2026-10-25T11:00:00Z',future='2026-10-25T13:00:00Z';
const config={enabled:true,intervalHours:1,workerTimeoutMinutes:40,releaseTimeoutMinutes:35,publishAndroid:true,androidTimeoutMinutes:30};
let checks=0;
function check(actual,expected){assert.deepEqual(actual,expected);checks++;}
check(validConfig(config),true);
for(const intervalHours of [0,-1,NaN,25,'1'])check(validConfig({...config,intervalHours}),false);
check(validConfig({...config,workerTimeoutMinutes:3}),false);
check(validConfig({...config,androidTimeoutMinutes:1}),false);
check(due({},now),true);check(due({nextRunUtc:'invalid'},now),true);
check(due({nextRunUtc:past},now),true);check(due({nextRunUtc:future},now),false);
check(due({nextRunUtc:new Date(now).toISOString()},now),true);
const act=(state,opts={})=>nextAction(config,state,{now,...opts});
check(act({nextRunUtc:past,pendingPublish:'waiting-for-desktop'}),'optimize');
check(act({nextRunUtc:past,pendingPublish:'failed',publishRetryAfterUtc:future}),'optimize');
check(act({nextRunUtc:past,pendingAndroid:{version:'old'}}),'optimize');
check(act({nextRunUtc:future,pendingPublish:'waiting-for-player'}),'wait');
check(act({nextRunUtc:future,pendingPublish:'failed',publishRetryAfterUtc:future}),'wait');
check(act({nextRunUtc:future,pendingPublish:'failed',publishRetryAfterUtc:past}),'wait');
check(act({nextRunUtc:future,pendingAndroid:{version:'v1'}}),'wait');
check(act({nextRunUtc:future,pendingPublish:'v1',publishRetryAfterUtc:future,pendingAndroid:{version:'v1'}}),'wait');
check(act({nextRunUtc:future,pendingAndroid:{version:'v1'},androidRetryAfterUtc:future}),'wait');
check(act({nextRunUtc:future}),'wait');
check(act({nextRunUtc:past},{held:true}),'held');
check(nextAction({...config,enabled:false},{nextRunUtc:past},{now}),'disabled');
check(act({nextRunUtc:past},{held:true,probe:true}),'probe');
check(act({nextRunUtc:future,pendingSnapshot:{version:'ready'}}),'enqueue');
check(act({nextRunUtc:past,pendingSnapshot:{version:'ready'}}),'enqueue');
check(act({nextRunUtc:past,pendingSnapshot:{version:'ready'}},{held:true}),'held');
console.log('HOURLY_AUTOMATION_CHECKS_OK: '+checks+' due-time, deferred-release, retry, Android and hold assertions.');
